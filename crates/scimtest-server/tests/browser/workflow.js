async page => {
  const info = __INFO__;
  const check = (value, message) => { if (!value) throw new Error(message); };
  const call = async value => {
    const response = await fetch(info.control, {method:'POST', headers:{authorization:'Bearer '+info.control_token,'content-type':'application/json'}, body:JSON.stringify(value)});
    check(response.ok, 'Fixture control failed');
    return response.json();
  };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.context().clearCookies();
  await call({action:'user',id:101,login:'rselbach'});
  await page.goto(info.dashboard+'/');
  await page.getByRole('link',{name:'Sign in with GitHub'}).click();
  await page.getByRole('link',{name:'Approve local test sign-in'}).click();
  await page.waitForURL(info.dashboard+'/dashboard');
  const adminCookie = (await page.context().cookies()).find(cookie => cookie.name === 'scimtest_session');
  check(adminCookie && adminCookie.httpOnly && adminCookie.sameSite === 'Lax', 'Missing protected dashboard session');
  const create = page.locator('form[action="/dashboard/applications/create"]');
  await create.locator('[name=name]').fill('Greendale Browser Classroom');
  await create.locator('[name=public_key]').fill(info.public_key);
  await create.locator('[name=routes]').fill('GET /oidc/{slug}/jwks');
  await create.getByRole('button',{name:'create application'}).click();
  await page.waitForURL(info.dashboard+'/dashboard#applications');
  let profile = page.locator('.profile').filter({hasText:'Greendale Browser Classroom'});
  await profile.locator('summary').click();
  await profile.locator('[name=name]').fill('Greendale Browser Study Group');
  await profile.getByRole('button',{name:'save application'}).click();
  await page.waitForURL(info.dashboard+'/dashboard#applications');
  profile = page.locator('.profile').filter({hasText:'Greendale Browser Study Group'});
  await profile.getByRole('button',{name:'delete',exact:true}).click();
  await profile.getByRole('button',{name:'cancel',exact:true}).click();
  check(await profile.count() === 1, 'Cancel deleted the profile');
  await profile.getByRole('button',{name:'delete',exact:true}).click();
  await profile.getByRole('button',{name:'yes',exact:true}).click();
  await page.waitForURL(info.dashboard+'/dashboard#applications');
  check(await page.locator('.profile').count() === 1, 'Profile delete did not persist');
  await call({action:'user',id:101,login:'troy-barnes'});
  const first = await call({action:'enroll',seed:24});
  await page.goto(first.url);
  check(await page.locator('.verification-code').innerText() === first.code, 'Verification code mismatch');
  await page.setViewportSize({width:390,height:780});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Confirmation overflows the viewport');
  await page.screenshot({path:info.artifacts+'/hosted-browser-'+info.backend.toLowerCase()+'-confirmation.png',fullPage:true});
  await page.getByRole('button',{name:'Continue with GitHub'}).click();
  await page.getByRole('link',{name:'Approve local test sign-in'}).click();
  await page.getByRole('heading',{name:'Installation authorized'}).waitFor();
  check((await page.context().cookies()).find(cookie => cookie.name === 'scimtest_session').value === adminCookie.value, 'Enrollment replaced the dashboard session');
  await page.setViewportSize({width:1100,height:850});
  await page.goto(info.dashboard+'/dashboard');
  check(await page.locator('#tunnel-count').innerText() === '0', 'Unexpected tunnel before connection');
  const connected = await call({action:'connect',seed:24});
  await page.waitForFunction(() => document.getElementById('tunnel-count').textContent === '1', null, {timeout:12000});
  check((await page.locator('#tunnel-list').innerText()).includes(connected.url), 'Refresh did not display the tunnel');
  await page.screenshot({path:info.artifacts+'/hosted-browser-'+info.backend.toLowerCase()+'-dashboard.png',fullPage:true});
  const second = await call({action:'enroll',seed:25});
  await page.goto(second.handoff);
  await page.getByRole('link',{name:'Approve local test sign-in'}).click();
  await page.getByRole('button',{name:'Disconnect and continue'}).waitFor();
  check(await page.locator('header').count() === 1 && await page.getByRole('heading',{name:'Make room for this installation'}).count() === 1, 'Replacement page duplicated its content');
  await page.setViewportSize({width:390,height:780});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Replacement overflows the viewport');
  await page.screenshot({path:info.artifacts+'/hosted-browser-'+info.backend.toLowerCase()+'-replacement.png',fullPage:true});
  await page.getByRole('button',{name:'Disconnect and continue'}).click();
  await page.getByRole('heading',{name:'Installation authorized'}).waitFor();
  const replacement = await call({action:'connect',seed:25});
  let snapshot = await call({action:'snapshot'});
  check(snapshot.profiles.find(profile => profile.id === info.profile).instances[first.instance].revoked, 'Replacement did not revoke the old identity');
  check(replacement.url !== connected.url, 'Replacement reused the revoked name');
  await page.setViewportSize({width:1100,height:850});
  await page.goto(info.dashboard+'/dashboard');
  const reservation = page.locator('.reservation').filter({hasText:second.instance});
  await reservation.getByRole('button',{name:'revoke',exact:true}).click();
  await reservation.getByRole('button',{name:'yes',exact:true}).click();
  await page.waitForURL(info.dashboard+'/dashboard#reserved-names');
  await page.waitForFunction(() => document.getElementById('tunnel-count').textContent === '0', null, {timeout:12000});
  await page.locator('.reservation').filter({hasText:second.instance}).getByRole('button',{name:'restore',exact:true}).click();
  await page.waitForURL(info.dashboard+'/dashboard#reserved-names');
  const restored = await call({action:'connect',seed:25});
  check(restored.url === replacement.url, 'Restoring changed the saved public name');
  const released = page.locator('.reservation').filter({hasText:second.instance});
  await released.getByRole('button',{name:'release',exact:true}).click();
  await released.getByRole('button',{name:'yes',exact:true}).click();
  await page.waitForURL(info.dashboard+'/dashboard#reserved-names');
  check((await page.locator('.reservation').filter({hasText:second.instance}).innerText()).includes('name released'), 'Name release did not render');
  snapshot = await call({action:'snapshot'});
  check(snapshot.profiles.find(profile => profile.id === info.profile).instances[second.instance].tunnel_id === '', 'Name release did not persist');
  await page.getByRole('button',{name:'sign out',exact:true}).click();
  await page.waitForURL(info.dashboard+'/');
  check(!(await page.context().cookies()).some(cookie => cookie.name === 'scimtest_session'), 'Logout retained the browser session');
  check(errors.length === 0, 'Browser page errors: '+errors.join('; '));
  return {backend:info.backend,passed:true,checks:['OAuth browser callback and session cookie','profile create/edit/delete with cancel/confirm','confirmation code and responsive layout','installation approval without changing admin session','live tunnel refresh','connected installation replacement','revocation and restore','saved name release','logout'],snapshot,errors};
}
